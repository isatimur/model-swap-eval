"""build_report.py - Step 6: assemble outputs/report.md from grade.py/judge.py's real numbers.

grade.py and judge.py already compute everything a decision report needs - they just print it
and (for judge.py) persist a per-model aggregate. This script reads outputs/grade_agg.json and
outputs/judge_agg.json (whichever exist) plus tasks.py, and mechanically fills the tradeoff
table, the tied-vs-worse reading, and the limitations paragraph from templates/report_template.md
- eliminating the hand-transcription step where a number gets mistyped from the console into
the report.

It deliberately does NOT decide anything. The "acceptable savings-per-quality-point ratio is a
business decision the user makes" (rigor.md) - the Verdict, Recommendation-per-task, and
Deployment-notes sections are exactly that judgment call, and are left as clearly marked
<FILL IN> placeholders. A report with everything filled in, including those sections, was
generated by a tool that skipped the one step this whole methodology exists to protect.

Usage:  python3 build_report.py
Needs:  tasks.py, outputs/grade_agg.json (from grade.py) and/or outputs/judge_agg.json (from judge.py)
Output: outputs/report.md + a console echo
"""
import json, os, statistics, sys
from datetime import date, datetime, timezone
from tasks import TASKS, MODELS, SEEDS, FRONTIER

GRADE = json.load(open("outputs/grade_agg.json")) if os.path.exists("outputs/grade_agg.json") else None
JUDGE = json.load(open("outputs/judge_agg.json")) if os.path.exists("outputs/judge_agg.json") else None
if GRADE is None and JUDGE is None:
    sys.exit("no outputs/grade_agg.json or outputs/judge_agg.json found - run grade.py "
             "(and judge.py, for subjective tasks) first.")

FILL = "<FILL IN - business call, see table above>"


def short(m): return m.split("/")[-1]


def fmt_pct(x, dp=1): return "n/a" if x is None else f"{x:.{dp}f}%"
def fmt_money(x): return "n/a" if x is None else f"${x:.4f}"
def fmt_num(x, dp=2): return "n/a" if x is None else f"{x:.{dp}f}"


n_cases = sum(len(t["cases"]) for t in TASKS)
n_models = len(MODELS)
n_seeds = len(SEEDS)
n_cells = n_models * n_cases * n_seeds

cost_by_model = (GRADE or {}).get("cost", {}).get("models", {}) or {}
# A null mean_cost means grade.py could not price that model (no PRICING entry) - it is UNKNOWN,
# not zero. Treating it as 0 here would understate the sweep's real cost, so the total reads n/a.
unpriced_models = [m for m, v in cost_by_model.items() if v.get("mean_cost") is None]
measured_total = (sum(v["mean_cost"] * v["n"] for v in cost_by_model.values())
                  if cost_by_model and not unpriced_models else None)

lines = []
def emit(s=""): lines.append(s)

emit(f"# Migration decision report - {', '.join(t['task'] for t in TASKS)}")
emit()
emit(f"**Date:** {date.today().isoformat()} - **Incumbent:** {FRONTIER} - "
     f"**Task volume:** {FILL} (calls/month, $/month)")
emit(f"**Harness:** {n_models} models x {n_cases} cases x {n_seeds} seeds = {n_cells} cells, "
     f"provider-pinned - measured sweep cost: {fmt_money(measured_total)}"
     + (f" (cost UNKNOWN for {', '.join(short(m) for m in unpriced_models)} - no PRICING entry in "
        f"tasks.py; this is not $0)" if unpriced_models else "")
     + (" (excludes judge panel API cost, not tracked separately)" if JUDGE else ""))
emit(f"**Golden refs validated by:** {FILL} (grade.py already refuses to run on an unvalidated ref, "
     f"but WHO signed off is not machine-checkable)")
emit()
emit("## Verdict (one paragraph, up front)")
emit()
emit(FILL + " - swap / swap-with-guard / optimize-first / keep frontier, per task, with the "
     "projected annual savings at stated volume. If the top is a statistical tie, say so.")
emit()


def worse_and_tied(models_by_verdict_key, verdict_key="verdict"):
    tied = [m for m, v in models_by_verdict_key.items() if "CLEARLY WORSE" not in v[verdict_key]]
    worse = [m for m, v in models_by_verdict_key.items() if "CLEARLY WORSE" in v[verdict_key]]
    return tied, worse


if GRADE and GRADE.get("deterministic"):
    det = GRADE["deterministic"]
    emit("## The tradeoff table - deterministic tasks (case-clustered pass-rate)")
    emit()
    emit("| Candidate | Pass-rate (mean +/- 95% CI) | Accuracy loss vs frontier | $/call (mean +/- stderr) "
         "| $ saved | Latency p90 | Verdict |")
    emit("|---|---|---|---|---|---|---|")
    fr_rate = det["models"].get(FRONTIER, {}).get("pass_rate")
    for m, v in sorted(det["models"].items(), key=lambda kv: -kv[1]["pass_rate"]):
        ci = f"{v['se']*196:.1f}pp" if v.get("se") is not None else "n/a"
        loss = None
        if not v["is_frontier"] and fr_rate:
            loss = (fr_rate - v["pass_rate"]) / fr_rate * 100
        c = cost_by_model.get(m, {})
        emit(f"| {short(m)}{' (baseline)' if v['is_frontier'] else ''} "
             f"| {v['pass_rate']*100:.1f}% +/- {ci} | {'-' if v['is_frontier'] else fmt_pct(loss)} "
             f"| {fmt_money(c.get('mean_cost'))} +/- {fmt_money(c.get('se_cost'))} "
             f"| {'-' if v['is_frontier'] else fmt_pct(c.get('saved_pct'))} "
             f"| {fmt_num(c.get('p90_latency'), 1)}s | {v['verdict']} |")
    emit()
    emit(f"Quality source: deterministic pass-rate, CASE-clustered, n_cases={det['n_cases']}. "
         + (f"Minimum difference detectable at this n: ~{det['mdd_pp']:.0f}pp - smaller gaps are "
            f"undetectable here." if det.get("mdd_pp") is not None else ""))
    emit()
    tied, worse = worse_and_tied(det["models"])
    emit("### Statistical reading (deterministic)")
    emit(f"- **Top cluster (statistically tied):** {', '.join(short(m) for m in tied) or 'none'}")
    emit(f"- **Clearly worse:** {', '.join(short(m) for m in worse) or 'none'}")
    emit()

if JUDGE and JUDGE.get("agg"):
    agg = JUDGE["agg"]
    emit("## The tradeoff table - subjective tasks (blind multi-family panel)")
    emit()
    emit("| Candidate | Quality (mean +/- std [95% CI]) | Accuracy loss vs frontier | $/call (mean +/- stderr) "
         "| $ saved | Latency p90 | Verdict |")
    emit("|---|---|---|---|---|---|---|")
    for m, v in sorted(agg.items(), key=lambda kv: -kv[1]["mean"]):
        ci_lo, ci_hi = v["mean"] - 1.96 * v["stderr"], v["mean"] + 1.96 * v["stderr"]
        c = cost_by_model.get(m, {})
        loss = v.get("loss_vs_frontier_pct")
        emit(f"| {short(m)}{' (baseline)' if v.get('is_frontier') else ''} "
             f"| {v['mean']:.2f} +/- {v['std']:.2f} [{ci_lo:.2f}-{ci_hi:.2f}] "
             f"| {'-' if v.get('is_frontier') else fmt_pct(loss)} "
             f"| {fmt_money(c.get('mean_cost'))} +/- {fmt_money(c.get('se_cost'))} "
             f"| {'-' if v.get('is_frontier') else fmt_pct(c.get('saved_pct'))} "
             f"| {fmt_num(c.get('p90_latency'), 1)}s | {v.get('verdict', 'n/a')} |")
    emit()
    emit(f"Quality source: blind panel, n={next(iter(agg.values()))['n']} scores/model "
         f"({n_seeds} seeds x cases x judges). Judge fabrication flags are ADVISORY - trust "
         f"grade.py's deterministic fabrication check over these.")
    emit()
    if JUDGE.get("drops"):
        emit(f"NOTE: {JUDGE['drops']} judge call(s) never parsed and were dropped.")
    if JUDGE.get("missing"):
        emit(f"NOTE: {JUDGE['missing']} candidate score(s) were absent from an otherwise-parsed judge reply.")
    emit()
    tied, worse = worse_and_tied(agg)
    emit("### Statistical reading (subjective panel)")
    emit(f"- **Top cluster (statistically tied):** {', '.join(short(m) for m in tied) or 'none'}")
    emit(f"- **Clearly worse:** {', '.join(short(m) for m in worse) or 'none'}")
    emit()

emit("## Deterministic findings (these carry more weight than the panel)")
emit()
emit("Fabrication rates, trap/boundary-case results, and parse-failure counts are persisted "
     "per-(task,case,model) in outputs/grade_agg.json's \"cases\" array (grade.py) - run "
     "build_report_html.py for a rendered per-case grid, or copy the relevant lines from "
     "grade.py's console output here.")
emit()
emit("## Recommendation per task")
emit()
emit("| Task | Recommendation | Model (+ provider pin, quant) | Guard required | Projected annual savings |")
emit("|---|---|---|---|---|")
for t in TASKS:
    emit(f"| {t['task']} | {FILL} | {FILL} | {FILL} | {FILL} |")
emit()
emit("## Deployment notes")
emit()
emit(FILL + " - orchestration pattern, guards wired into production, rollback plan, re-run triggers.")
emit()
emit("## Limitations (mandatory - do not trim)")
emit()
n_judge_scores = next(iter(JUDGE["agg"].values()))["n"] if JUDGE and JUDGE.get("agg") else None
emit(f"This verdict is based on {n_cases} case(s) x {n_seeds} seed(s) per model"
     + (f" ({n_judge_scores} panel scores/model)" if n_judge_scores else "")
     + f", on THESE prompts, THESE pinned providers, as of {date.today().isoformat()}. "
     "It is not a general model ranking. Prices and the model field turn over monthly - "
     "treat this report as perishable; re-run on prompt change, pin/quant change, a notable "
     "new model, or quarterly.")
emit()

report = "\n".join(lines)
os.makedirs("outputs", exist_ok=True)
open("outputs/report.md", "w").write(report)
print(report)
print("\n---\nsaved -> outputs/report.md  (fill every <FILL IN> before calling this a decision)",
      file=sys.stderr)
